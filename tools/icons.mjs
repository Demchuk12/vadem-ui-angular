// Generates projects/ui/icon/src/core/icons.ts from a pinned Lucide release.
// Every SVG element is converted to a path `d` string so all adapters render one element type.
// Usage: npm run icons   (network needed; output is committed)
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const config = JSON.parse(readFileSync(resolve(import.meta.dirname, 'icons.json'), 'utf8'));
const CDN = `https://unpkg.com/lucide-static@${config.lucideVersion}`;

const num = (v) => Number(v ?? 0);
const attrs = (tag) =>
  Object.fromEntries([...tag.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]));

function toPath(name, a) {
  switch (name) {
    case 'path':
      return a.d;
    case 'line':
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline':
    case 'polygon': {
      const [first, ...rest] = a.points.trim().split(/[\s,]+/).reduce((pts, v, i, all) => {
        if (i % 2 === 0) pts.push(`${v} ${all[i + 1]}`);
        return pts;
      }, []);
      return `M${first}${rest.map((p) => `L${p}`).join('')}${name === 'polygon' ? 'Z' : ''}`;
    }
    case 'circle':
    case 'ellipse': {
      const cx = num(a.cx), cy = num(a.cy);
      const rx = num(a.rx ?? a.r), ry = num(a.ry ?? a.r);
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${rx * 2} 0a${rx} ${ry} 0 1 0 ${-rx * 2} 0Z`;
    }
    case 'rect': {
      const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height);
      const r = Math.min(num(a.rx ?? a.ry), w / 2, h / 2);
      if (!r) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return (
        `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}` +
        `a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}` +
        `v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`
      );
    }
    default:
      throw new Error(`Unsupported SVG element <${name}>`);
  }
}

const entries = [];
for (const [vdName, lucideName] of Object.entries(config.icons)) {
  const res = await fetch(`${CDN}/icons/${lucideName}.svg`);
  if (!res.ok) throw new Error(`${lucideName}: HTTP ${res.status}`);
  const svg = await res.text();
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  const paths = [...body.matchAll(/<(\w+)\b([^>]*?)\/?>/g)].map(([, el, rest]) => toPath(el, attrs(rest)));
  entries.push([vdName, lucideName, paths]);
  console.log(`✓ ${vdName} <- ${lucideName} (${paths.length})`);
}

const license = await (await fetch(`${CDN}/LICENSE`)).text();
writeFileSync(resolve(root, 'projects/ui/icon/LICENSE-lucide.txt'), license);

const out = `/**
 * @license
 * Icon geometry from Lucide ${config.lucideVersion} (https://lucide.dev), ISC License,
 * Copyright (c) Lucide Icons and Contributors. Parts derived from Feather (MIT),
 * Copyright (c) 2013-2023 Cole Bemis. Full text: LICENSE-lucide.txt
 */

// GENERATED by tools/icons.mjs from tools/icons.json - do not edit by hand.

/**
 * Vadem icon set. Framework-agnostic data: every icon is a list of SVG path \`d\` strings on a
 * 24x24 grid, rendered by adapters with stroke 1.5, round caps and joins, currentColor.
 */
export const VD_ICONS = {
${entries.map(([n, l, p]) => `  /** lucide: ${l} */\n  '${n}': [\n${p.map((d) => `    '${d}',`).join('\n')}\n  ],`).join('\n')}
} as const satisfies Record<string, readonly string[]>;

export type VdIconName = keyof typeof VD_ICONS;

/** Icons that point in the reading direction and must be mirrored in RTL. */
export const VD_DIRECTIONAL_ICONS: ReadonlySet<VdIconName> = new Set<VdIconName>([
${config.directional.map((n) => `  '${n}',`).join('\n')}
]);

export const VD_ICON_NAMES = Object.keys(VD_ICONS) as VdIconName[];
`;
writeFileSync(resolve(root, 'projects/ui/icon/src/core/icons.ts'), out);
console.log(`Wrote ${entries.length} icons.`);
